<#
.SYNOPSIS
    修复 GitHub 网页间歇性打不开（ERR_CONNECTION_TIMED_OUT）的问题。

.DESCRIPTION
    本机 DNS 通常能正确解析 github.com，但运营商链路对 GitHub 的部分 IP 存在
    间歇性 443 阻断，表现为“有时能上、有时超时”。

    本脚本从 GitHub 官方公布的 IP 段（api.github.com/meta）中逐个实测：
    TCP 443 连通性 + 延迟 + 稳定性，然后选出当前网络最可靠的一批 IP
    写入 hosts 文件，从而绕开被阻断的地址。

.PARAMETER TestOnly
    只测试并输出报告，不修改系统。建议首次使用先跑这个。

.PARAMETER Restore
    卸载：移除本脚本写入的 hosts 条目并刷新 DNS 缓存。

.PARAMETER Top
    取前 N 个 IP 写入 hosts（默认 3）。

.PARAMETER NoPause
    结束后不等待按键（便于自动化/脚本调用）。

.EXAMPLE
    powershell -ExecutionPolicy Bypass -File .\fix-github.ps1 -TestOnly

.EXAMPLE
    # 在“管理员”终端中执行
    powershell -ExecutionPolicy Bypass -File .\fix-github.ps1

.EXAMPLE
    powershell -ExecutionPolicy Bypass -File .\fix-github.ps1 -Restore

.NOTES
    作者   : CSQ798
    许可   : MIT
    仓库   : https://github.com/CSQ798/github-connectivity-fix
    版本   : 1.0.0
    修改 hosts 需要管理员权限；脚本可重复运行，每次都会重新选优。
#>
#Requires -Version 5.1
[CmdletBinding()]
param(
    [switch]$TestOnly,
    [switch]$Restore,
    [int]$Top = 3,
    [switch]$NoPause
)

$ErrorActionPreference = 'Stop'
$ScriptVersion = '1.0.0'

$HostsPath  = Join-Path $env:SystemRoot 'System32\drivers\etc\hosts'
$BeginMark  = '# >>> GitHub Fix (auto-generated by fix-github.ps1) >>>'
$EndMark    = '# <<< GitHub Fix <<<'

# 输出目录：优先脚本所在目录；不可写则退回临时目录
$ScriptDir = if ($PSScriptRoot) { $PSScriptRoot } else { (Get-Location).Path }
if (-not (Test-Path $ScriptDir)) { $ScriptDir = $env:TEMP }
$BackupPath = Join-Path $ScriptDir 'hosts.githubfix.bak'

# ---------------------------------------------------------------- 自我修复编码
# 本脚本含中文，必须是“UTF-8 带 BOM”，否则 Windows PowerShell 5.1 会按 GBK
# 读取导致乱码与语法错误。若用户编辑器保存成无 BOM，这里自动补回。
function Repair-SelfEncoding {
    if (-not $PSCommandPath) { return }
    try {
        $bytes = [System.IO.File]::ReadAllBytes($PSCommandPath)
        if ($bytes.Length -ge 3 -and $bytes[0] -eq 0xEF -and $bytes[1] -eq 0xBB -and $bytes[2] -eq 0xBF) { return }
        $text = [System.Text.Encoding]::UTF8.GetString($bytes)
        [System.IO.File]::WriteAllText($PSCommandPath, $text, (New-Object System.Text.UTF8Encoding($true)))
        Write-Host '[i] 已为脚本文件补写 UTF-8 BOM（避免中文乱码）。' -ForegroundColor Yellow
    } catch {
        # 只读位置或权限不足时忽略，不影响主流程
    }
}

# ---------------------------------------------------------------- GitHub 官方 IP
# 来源：https://api.github.com/meta 的 web / git 字段
# 这些是 GitHub 真实边缘节点地址，改 hosts 不会被证书校验拒绝。
$Candidates = @(
    '20.27.177.113', '20.27.177.114', '20.27.177.119', '20.27.177.118'        # 亚太（延迟最低，优先）
    '20.205.243.166', '20.205.243.168', '20.205.243.161', '20.205.243.160'    # 亚太
    '4.237.22.38', '4.237.22.36', '4.237.22.40'                               # 亚太
    '20.201.28.151', '20.201.28.152'
    '20.207.73.82', '20.200.245.247', '20.175.192.147', '20.233.83.145'
    '20.29.134.23', '20.217.135.5', '4.208.26.197', '20.26.156.215'
    '20.199.39.232', '4.225.11.194', '4.249.131.164'
    '140.82.112.3', '140.82.113.3', '140.82.114.3', '140.82.116.3'            # 美国（延迟较高，备用）
)

# 需要接管的域名（均为 GitHub 官方 web/git 端点，全站证书通用）
$TargetDomains = @(
    'github.com'
    'api.github.com'
    'codeload.github.com'
    'raw.githubusercontent.com'
    'objects.githubusercontent.com'
)

function Write-Head($t) {
    Write-Host "`n$t" -ForegroundColor Cyan
    Write-Host ('-' * 60) -ForegroundColor DarkGray
}

function Test-Port443 {
    param([string]$IP, [int]$TimeoutMs = 3000)
    $client = New-Object System.Net.Sockets.TcpClient
    $sw = [System.Diagnostics.Stopwatch]::StartNew()
    try {
        $iar = $client.BeginConnect($IP, 443, $null, $null)
        if ($iar.AsyncWaitHandle.WaitOne($TimeoutMs, $false)) {
            $client.EndConnect($iar)
            $sw.Stop()
            return [pscustomobject]@{ Ok = $true; Ms = $sw.ElapsedMilliseconds }
        }
        return [pscustomobject]@{ Ok = $false; Ms = $TimeoutMs }
    } catch {
        return [pscustomobject]@{ Ok = $false; Ms = $TimeoutMs }
    } finally { $client.Close() }
}

# ---------------------------------------------------------------- 主流程
Repair-SelfEncoding

Write-Host "GitHub 连通性修复脚本 v$ScriptVersion" -ForegroundColor White
Write-Host "hosts : $HostsPath"
Write-Host "工作目录: $ScriptDir"

$isAdmin = ([Security.Principal.WindowsPrincipal][Security.Principal.WindowsIdentity]::GetCurrent()
           ).IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)

function Pause-IfNeeded {
    if ($NoPause) { return }
    Write-Host ''
    if ($Host.Name -eq 'ConsoleHost') {
        Write-Host '按任意键退出...' -ForegroundColor DarkGray
        try { $null = $Host.UI.RawUI.ReadKey('NoEcho,IncludeKeyDown') } catch { }
    }
}

# --- 卸载模式 ---
if ($Restore) {
    if (-not $isAdmin) {
        Write-Host "`n[!] 需要管理员权限才能修改 hosts 文件。" -ForegroundColor Red
        Pause-IfNeeded
        exit 1
    }
    $content = Get-Content $HostsPath -Raw
    if ($null -eq $content) { $content = '' }
    if ($content -match [regex]::Escape($BeginMark)) {
        $new = [regex]::Replace($content, "(?ms)^\s*$([regex]::Escape($BeginMark)).*?$([regex]::Escape($EndMark))\s*\r?\n?", '')
        Set-Content -Path $HostsPath -Value $new -Encoding ASCII -NoNewline
        Write-Host "`n[OK] 已移除 hosts 中的 GitHub Fix 条目。" -ForegroundColor Green
    } else {
        Write-Host "`n[i] hosts 中没有找到本脚本写入的条目，无需清理。" -ForegroundColor Yellow
    }
    ipconfig /flushdns | Out-Null
    Write-Host "[OK] DNS 缓存已刷新。" -ForegroundColor Green
    Write-Host "提示：浏览器可能仍缓存了旧结果，建议完全关闭后重开。" -ForegroundColor DarkGray
    Pause-IfNeeded
    exit 0
}

# --- 1) 实测 ---
Write-Head "[1/4] 正在实测 $($Candidates.Count) 个 GitHub 官方 IP（TCP 443，每 IP 探测 5 次）..."
Write-Host '     最长约需 5-7 分钟，请勿关闭窗口。' -ForegroundColor DarkGray

$ProbeCount = 5
$results = @()
foreach ($ip in $Candidates) {
    $ok = 0
    $times = @()
    for ($i = 1; $i -le $ProbeCount; $i++) {
        $r = Test-Port443 -IP $ip -TimeoutMs 3000
        if ($r.Ok) { $ok++; $times += $r.Ms }
    }
    $avg = if ($times.Count) { [int](($times | Measure-Object -Average).Average) } else { 99999 }
    $results += [pscustomobject]@{ IP = $ip; Success = $ok; Total = $ProbeCount; AvgMs = $avg }

    $bar   = if ($ok -eq $ProbeCount) { 'OK  ' } elseif ($ok -gt 0) { 'PART' } else { 'FAIL' }
    $color = if ($ok -eq $ProbeCount) { 'Green' } elseif ($ok -gt 0) { 'Yellow' } else { 'DarkGray' }
    Write-Host ("  [{0}] {1,-16} {2}/{3} 成功  平均 {4} ms" -f $bar, $ip, $ok, $ProbeCount, $avg) -ForegroundColor $color
}

$viable = $results |
          Where-Object { $_.Success -ge [math]::Ceiling($ProbeCount * 0.6) } |
          Sort-Object -Property @{Expression = 'Success'; Descending = $true },
                                @{Expression = 'AvgMs';   Ascending  = $true }

if (-not $viable) {
    Write-Host "`n[X] 所有候选 IP 当前都不可达。" -ForegroundColor Red
    Write-Host "    说明当前网络对 GitHub 做了全面阻断，改 hosts 无效。" -ForegroundColor Yellow
    Write-Host "    这种情况下只能使用代理 / VPN 访问 GitHub。" -ForegroundColor Yellow
    Pause-IfNeeded
    exit 2
}

$picked = $viable | Select-Object -First ([math]::Max(1, $Top))

Write-Head "[2/4] 选定当前最优 IP（成功率优先，延迟次之）"
$picked | ForEach-Object {
    Write-Host ("  {0,-16} {1}/{2} 成功  {3} ms" -f $_.IP, $_.Success, $_.Total, $_.AvgMs) -ForegroundColor Green
}

# --- 2) 生成 hosts 区块 ---
$entries = @{}
$idx = 0
foreach ($name in $TargetDomains) {
    $list = @()
    for ($k = 0; $k -lt $picked.Count; $k++) {
        $list += $picked[($idx + $k) % $picked.Count].IP
    }
    $entries[$name] = $list
    $idx++
}

$block = @()
$block += $BeginMark
$block += "# 生成时间: $(Get-Date -Format 'yyyy-MM-dd HH:mm:ss')"
$block += "# 由 fix-github.ps1 v$ScriptVersion 自动生成，删除本区块即可恢复原状。"
foreach ($name in $TargetDomains) {
    foreach ($ip in ($entries[$name] | Select-Object -Unique)) {
        $block += ('{0,-16} {1}' -f $ip, $name)
    }
}
$block += $EndMark

Write-Head "[3/4] 待写入 hosts 的内容"
$block | ForEach-Object { Write-Host "  $_" -ForegroundColor DarkCyan }

if ($TestOnly) {
    Write-Host "`n[i] -TestOnly 模式：未修改任何系统设置。" -ForegroundColor Yellow
    Write-Host "    确认无误后，去掉 -TestOnly 并以管理员身份重新运行即可应用。" -ForegroundColor Yellow
    Pause-IfNeeded
    exit 0
}

if (-not $isAdmin) {
    Write-Host "`n[!] 需要管理员权限才能修改 hosts 文件。" -ForegroundColor Red
    Write-Host "    请右键开始菜单 -> 终端(管理员) / Windows PowerShell(管理员)，再运行本脚本。" -ForegroundColor Yellow
    Pause-IfNeeded
    exit 1
}

# --- 3) 备份并写入 ---
if (-not (Test-Path $BackupPath)) {
    Copy-Item $HostsPath $BackupPath -Force
    Write-Host "`n[OK] 原始 hosts 已备份到: $BackupPath" -ForegroundColor Green
} else {
    Write-Host "`n[i] 备份已存在，保留较早的备份: $BackupPath" -ForegroundColor Yellow
}

$current = Get-Content $HostsPath -Raw
if ($null -eq $current) { $current = '' }
if ($current -match [regex]::Escape($BeginMark)) {
    $current = [regex]::Replace($current, "(?ms)^\s*$([regex]::Escape($BeginMark)).*?$([regex]::Escape($EndMark))\s*\r?\n?", '')
}
$newContent = $current.TrimEnd() + "`r`n`r`n" + ($block -join "`r`n") + "`r`n"
Set-Content -Path $HostsPath -Value $newContent -Encoding ASCII -NoNewline
Write-Host "[OK] hosts 已更新。" -ForegroundColor Green

ipconfig /flushdns | Out-Null
Write-Host "[OK] DNS 缓存已刷新。" -ForegroundColor Green

# --- 4) 验证 ---
Write-Head "[4/4] 验证"
try {
    $resolved = (Resolve-DnsName github.com -Type A -ErrorAction Stop |
                 Where-Object { $_.IPAddress } |
                 Select-Object -ExpandProperty IPAddress) -join ', '
    Write-Host "  github.com 现在解析为: $resolved" -ForegroundColor Green
    if ($resolved -match (($picked.IP | ForEach-Object { [regex]::Escape($_) }) -join '|')) {
        Write-Host "  [OK] 已生效，指向实测可用的 IP。" -ForegroundColor Green
    }
} catch {
    Write-Host "  解析查询失败: $($_.Exception.Message)" -ForegroundColor Yellow
}

$check = Test-Port443 -IP $picked[0].IP -TimeoutMs 4000
if ($check.Ok) {
    Write-Host "  [OK] 首选 IP $($picked[0].IP):443 连接正常（$($check.Ms) ms）" -ForegroundColor Green
} else {
    Write-Host "  [!] 首选 IP 当前连接失败，建议重新运行本脚本重新选优。" -ForegroundColor Yellow
}

Write-Host "`n完成！请完全关闭并重新打开浏览器（或清空浏览器 DNS 缓存）再访问 https://github.com" -ForegroundColor White
Write-Host "以后若再次打不开：以管理员身份重新运行本脚本即可自动换一批 IP。" -ForegroundColor White
Write-Host "恢复原状：运行本脚本加 -Restore，或还原备份：" -ForegroundColor White
Write-Host "  Copy-Item `"$BackupPath`" `"$HostsPath`" -Force" -ForegroundColor DarkGray
Pause-IfNeeded
